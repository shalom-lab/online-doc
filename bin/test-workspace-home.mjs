import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { workspaceHomes } from './pages/workspace-home.mjs';

const html = readFileSync('index.html', 'utf8');
assert.match(html, /我的文档库/);
assert.match(html, /id="editor"/);
assert.match(html, /<script defer src="\/library.js"><\/script>/);
assert.doesNotMatch(html, /Open Word, Excel|GENERATED by/);
assert.equal(readFileSync('public/library.html', 'utf8'), html);
const homes = workspaceHomes();
assert(homes.some(home => home.rel === 'zh-CN/index.html'));
assert(!homes.some(home => home.rel === 'index.html'), 'Generation must not overwrite the authored homepage');
for (const home of homes) assert.equal(home.html, html);

const source = readFileSync('public/library.js', 'utf8');
const base = source.match(/const APP_BASE = .*;/)[0];
for (const prefix of ['/', '/online-doc/']) {
  for (const route of ['', 'zh-CN/', 'library.html']) {
    const editor = runInNewContext(base + '\nnew URL("editor.html", APP_BASE).href', {
      URL,
      document: { currentScript: { src: `https://example.test${prefix}library.js` } },
      location: { href: `https://example.test${prefix}${route}` },
    });
    assert.equal(editor, `https://example.test${prefix}editor.html`);
  }
}
console.log('PASS: authored workspace homepage, locale aliases and editor URLs on root/subpath hosts');
